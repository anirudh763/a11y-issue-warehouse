"""Run every analysis/NN_*.sql against the warehouse; write results/*.csv and results/summary.md."""
import argparse
import csv
import pathlib
import sqlite3

HERE = pathlib.Path(__file__).parent


def run_sql_file(conn, path):
    """Execute one analysis file (a single SELECT). Returns (column names, rows)."""
    cur = conn.execute(pathlib.Path(path).read_text())
    return [d[0] for d in cur.description], cur.fetchall()


def md_table(cols, rows):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", default="data/warehouse.db")
    ap.add_argument("--out", default="results")
    args = ap.parse_args()
    conn = sqlite3.connect(args.db)
    out = pathlib.Path(args.out)
    out.mkdir(exist_ok=True)
    tables = {}
    for path in sorted(HERE.glob("[0-9][0-9]_*.sql")):
        cols, rows = run_sql_file(conn, path)
        tables[path.stem] = (cols, rows)
        with open(out / f"{path.stem}.csv", "w", newline="") as fh:
            csv.writer(fh, lineterminator="\n").writerows([cols] + rows)
        print(f"{path.name}: {len(rows)} rows -> {out / (path.stem + '.csv')}")

    counts = conn.execute(
        "SELECT (SELECT COUNT(*) FROM repos), COUNT(*), SUM(c.is_a11y), SUM(NOT c.is_a11y), "
        "(SELECT substr(collected_at, 1, 10) FROM load_runs ORDER BY id DESC LIMIT 1), "
        "(SELECT COUNT(*) FROM issues) "
        "FROM issues i JOIN issue_class c ON c.issue_id = i.id").fetchone()
    per_repo = conn.execute(
        "SELECT r.full_name AS repo, COALESCE(r.a11y_label, '(none)') AS a11y_label, "
        "SUM(c.is_a11y) AS accessibility, SUM(NOT c.is_a11y) AS other, "
        "SUM(c.is_a11y AND i.state = 'open') AS accessibility_open_now "
        "FROM issues i JOIN issue_class c ON c.issue_id = i.id JOIN repos r ON r.id = i.repo_id "
        "GROUP BY r.id ORDER BY accessibility DESC")
    per_repo = ([d[0] for d in per_repo.description], per_repo.fetchall())

    def pooled(name):
        cols, rows = tables[name]
        return cols[1:], [r[1:] for r in rows if r[0] == "(all repositories)"]

    cols4, rows4 = tables["04_label_cooccurrence"]
    summary = f"""# Summary

Generated by `python3 analysis/run_analysis.py` from `data/warehouse.db`
(data collected {counts[4]}). Full tables are the CSV files next to this file.

{counts[0]} repositories, {counts[5]} issues loaded, {counts[1]} classified: {counts[2]} accessibility
issues (carry the repository's accessibility label, or were returned by the keyword search
and really contain a search word) and {counts[3]} comparison issues. The other
{counts[5] - counts[1]} were returned by the keyword search without containing a search word and are
left out of every table below.

## Issues per repository

{md_table(*per_repo)}

## Days from open to close, all repositories pooled (closed issues only)

{md_table(*pooled("02_days_to_close"))}

## Still open one year after opening, all repositories pooled

{md_table(*pooled("03_open_after_one_year"))}

## Label that most often accompanies the accessibility label, per repository

{md_table(cols4, [r for r in rows4 if r[1] == 1])}

## Comparison sample date match

{md_table(*tables["05_comparison_date_match"])}

The pooled rows are dominated by the repositories with the most issues; see
`02_days_to_close.csv` and `03_open_after_one_year.csv` for per-repository rows.
"""
    (out / "summary.md").write_text(summary)
    print(f"wrote {out / 'summary.md'}")


if __name__ == "__main__":
    main()
