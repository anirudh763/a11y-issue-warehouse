"""Step 6: write results/results.md from the CSV files in results/.

Only numbers from the CSVs appear in the table; nothing here is typed in by hand. Run time
is not written here (it changes between runs); run_all.py prints it.
"""
import hashlib

import pandas as pd

from paths import BUILD, RAW, RESULTS, ROOT
from pipeline import CLASSIFIERS, N_FEATURES, N_FOLDS, NGRAM_RANGE

ORDER = list(CLASSIFIERS) + ["Keyword rule (reference, not trained)"]


def ms(row, metric):
    return f"{row[f'{metric}_mean']:.3f} ± {row[f'{metric}_sd']:.3f}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def by_classifier(df):
    return df.set_index("classifier").loc[[c for c in ORDER if c in set(df["classifier"])]]


def data_hashes():
    """SHA-256 of the inputs: all raw pages (path and bytes, sorted) and the built tables."""
    raw = hashlib.sha256()
    pages = sorted(RAW.rglob("*.json.gz"))
    for path in pages:
        raw.update(path.relative_to(ROOT).as_posix().encode() + b"\0")
        raw.update(path.read_bytes())
    rows = [("data/raw/ (all pages)", len(pages), raw.hexdigest())]
    for name in ("dataset.csv", "preprocessed.csv"):
        data = (BUILD / name).read_bytes()
        rows.append((f"reproduction/build/{name}", data.count(b"\n"),
                     hashlib.sha256(data).hexdigest()))
    return pd.DataFrame(rows, columns=["input", "files_or_lines", "sha256"])


def main():
    hashes = data_hashes()
    hashes.to_csv(RESULTS / "data_hashes.csv", index=False)
    dups = pd.read_csv(RESULTS / "duplicates.csv", dtype=str).set_index("property")["value"]
    props = pd.read_csv(RESULTS / "dataset_properties.csv").set_index("property")["value"]
    exp1 = by_classifier(pd.read_csv(RESULTS / "exp1_cv_summary.csv"))
    cv = pd.read_csv(RESULTS / "ext_cv_summary.csv")
    loao = pd.read_csv(RESULTS / "ext_loao_summary.csv")
    control = by_classifier(pd.read_csv(RESULTS / "control_shuffled.csv"))

    out = ["# Results (generated by src/make_report.py; do not edit by hand)", ""]
    out.append(
        f"Dataset: {props['issues']} GitHub issues from 15 Android apps, "
        f"{props['accessibility (label 1)']} accessibility and "
        f"{props['comparison (label 0)']} comparison. Text: description (issue body) only. "
        f"Features: feature hashing, {N_FEATURES} features, n-grams {NGRAM_RANGE[0]} to "
        f"{NGRAM_RANGE[1]}. Labels are weak labels: selected by repository labels and a keyword search, "
        "not hand-verified, so they are not ground truth. These scores are not comparable "
        "to the paper's (different data source, different labelling, different class ratio). "
        f"{dups['issues in those groups']} issues are in {dups['groups with more than one issue']} "
        "groups of exact or near duplicates (cosine >= 0.9); a group never crosses train and "
        "test.")
    out += ["", f"## Experiment 1: the paper's pipeline, {N_FOLDS}-fold stratified CV, raw text",
            "", "Mean ± SD over the 10 folds.", ""]
    out.append(table(["Classifier", "Accuracy", "Precision", "Recall", "F1", "AUC"],
                     [[c] + [ms(r, m) for m in ("accuracy", "precision", "recall", "f1", "auc")]
                      for c, r in exp1.iterrows()]))

    out += ["", "## Extension: leave-one-app-out and keyword masking", "",
            "F1 (AUC in brackets). 10-fold rows: mean over folds. Leave-one-app-out rows: "
            "pooled over all 15 held-out apps (each app scored by a model trained on the "
            "other 14, minus any near-duplicate of a held-out issue). Masked: accessib*, a11y, talkback/talk back and screen reader(s) "
            "removed from the description before preprocessing.", ""]
    cells = {}
    for _, r in cv.iterrows():
        cells[(r["classifier"], "cv", r["text"])] = f"{r['f1_mean']:.3f} ({r['auc_mean']:.3f})"
    for _, r in loao.iterrows():
        cells[(r["classifier"], "loao", r["text"])] = f"{r['f1']:.3f} ({r['auc']:.3f})"
    cols = [("cv", "raw"), ("cv", "masked"), ("loao", "raw"), ("loao", "masked")]
    out.append(table(["Classifier", "10-fold, raw", "10-fold, masked", "Leave-one-app-out, raw",
                      "Leave-one-app-out, masked"],
                     [[c] + [cells.get((c, e, t), "") for e, t in cols] for c in ORDER]))

    out += ["", "Per held-out app, masked text (F1 range and median over the 15 apps):", ""]
    lm = by_classifier(loao[loao["text"] == "masked"])
    out.append(table(["Classifier", "Min F1", "Median F1", "Max F1", "Median AUC"],
                     [[c, f"{r['per_app_f1_min']:.3f}", f"{r['per_app_f1_median']:.3f}",
                       f"{r['per_app_f1_max']:.3f}", f"{r['per_app_auc_median']:.3f}"]
                      for c, r in lm.iterrows()]))

    out += ["", "## Control: shuffled labels (10-fold, raw text)", "",
            "Labels permuted once (seed 0). Passes if mean AUC is within 0.05 of 0.5.", ""]
    out.append(table(["Classifier", "AUC", "F1", "Near chance"],
                     [[c, ms(r, "auc"), ms(r, "f1"), "yes" if r["near_chance"] else "NO"]
                      for c, r in control.iterrows()]))
    out += ["", "## Inputs (SHA-256)", ""]
    out.append(table(["Input", "Files or lines", "SHA-256"],
                     [[r["input"], r["files_or_lines"], f"`{r['sha256']}`"]
                      for _, r in hashes.iterrows()]))
    out.append("")
    (RESULTS / "results.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
